import Head from 'next/head'
import Image from 'next/legacy/image'
import { useRouter } from 'next/router'
import { Button, buttonVariants } from '~/components/ui/button'
import { imagesConfig } from '~/config/site'
import { cn } from '~/lib/utils'
import { useLuisterenStore } from '~/stores/gameModes/luisterenStore'

interface Props {
  children: React.ReactNode
  title: string
  backPath?: string
  classNameParent?: string
  shouldRenderBackButton?: boolean
  instrumentURL?: string | null
}

const ContentContainer: React.FC<Props> = ({
  children,
  title,
  classNameParent,
  backPath = '/',
  shouldRenderBackButton = true,
  instrumentURL = undefined,
}) => {
  const router = useRouter()
  const { shouldRenderCinieInContentContainer } = useLuisterenStore()

  return (
    <>
      <Head>
        <title>{title}</title>
        <meta name="description" content="Generated by create-t3-app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <section className="flex grow flex-col items-center justify-center">
        <div className="container mx-auto flex flex-col items-center justify-start gap-6 py-12">
          <div className="w-full rounded-2xl">
            <div className="relative flex w-full justify-between rounded-t-2xl bg-primary-foreground">
              <div className="relative size-24">
                {shouldRenderCinieInContentContainer && (
                  <Image
                    objectFit="contain"
                    layout="fill"
                    src={imagesConfig.cinie}
                    alt="cinie"
                    className=""
                    sizes="(max-width: 768px) 100vw, (max-width: 1200px) 50vw, 33vw"
                  />
                )}
              </div>

              <h2 className="flex items-center justify-center text-balance text-center text-xl md:text-3xl mx-2 font-extrabold">
                {title}
              </h2>

              <div className="relative size-24">
                {instrumentURL && (
                  <Image
                    layout="fill"
                    objectFit="contain"
                    src={instrumentURL}
                    alt="instrument"
                    className=""
                    sizes="(max-width: 768px) 100vw, (max-width: 1200px) 50vw, 33vw"
                  />
                )}
              </div>
            </div>
            <div
              className={cn('flex w-full flex-col items-center justify-between', classNameParent)}
            >
              {children}
            </div>
          </div>
          {shouldRenderBackButton && (
            <Button
              size={'lg'}
              onClick={() => {
                router.push(backPath)
              }}
            >
              <h3 className="text-xl">Terug</h3>
            </Button>
          )}
        </div>
      </section>
    </>
  )
}

export default ContentContainer
